#!/usr/bin/env python3
"""Generates Android string resources (values = fr, values-en, values-ar) from tools/strings_source.py."""
import os, sys, re
from xml.sax.saxutils import escape
sys.path.insert(0, os.path.dirname(__file__))
from strings_source import S, P

ROOT = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res")

def esc(s):
    s = escape(s).replace("'", "\\'").replace('"', '\\"')
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s

def write(folder, idx):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/generate_strings.py — edit tools/strings_source.py instead. -->', "<resources>"]
    for k, v in S.items():
        text = v[idx]
        attrs = ""
        if "%" in text and not re.search(r"%\d\$", text) and "%%" not in text:
            attrs += ' formatted="false"'
        lines.append(f'    <string name="{k}"{attrs}>{esc(text)}</string>')
    for k, v in P.items():
        lines.append(f'    <plurals name="{k}">')
        if idx == 2:
            for q, t in v[2].items():
                lines.append(f'        <item quantity="{q}">{esc(t)}</item>')
        else:
            one, other = v[idx]
            lines.append(f'        <item quantity="one">{esc(one)}</item>')
            if idx == 0:
                lines.append(f'        <item quantity="many">{esc(other)}</item>')
            lines.append(f'        <item quantity="other">{esc(other)}</item>')
        lines.append("    </plurals>")
    lines.append("</resources>")
    d = os.path.join(ROOT, folder)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "strings.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

for folder, idx in (("values", 0), ("values-en", 1), ("values-ar", 2)):
    write(folder, idx)
print(f"{len(S)} strings, {len(P)} plurals written")
